--
-- Name: process_backorder_fulfillment(uuid[], uuid, uuid); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.process_backorder_fulfillment(p_backorder_ids uuid[], p_company_id uuid, p_created_by uuid DEFAULT auth.uid()) RETURNS json
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_result JSON;
  v_customer_orders RECORD;
  v_new_order_id UUID;
  v_processed_count INTEGER := 0;
  v_total_value NUMERIC := 0;
BEGIN
  -- Group backorders by customer and create sales orders
  FOR v_customer_orders IN
    SELECT 
      bi.customer_id,
      c.name as customer_name,
      c.email as customer_email,
      c.phone as customer_phone,
      c.address as customer_address,
      array_agg(bi.id) as backorder_item_ids,
      array_agg(bi.product_id) as product_ids,
      array_agg(bi.quantity_backordered) as quantities,
      array_agg(bi.unit_price) as unit_prices,
      SUM(bi.quantity_backordered * bi.unit_price) as order_total
    FROM public.backorder_items bi
    JOIN public.customers c ON bi.customer_id = c.id
    WHERE bi.id = ANY(p_backorder_ids)
      AND bi.company_id = p_company_id
      AND bi.status = 'pending'
    GROUP BY bi.customer_id, c.name, c.email, c.phone, c.address
  LOOP
    -- Create new sales order
    INSERT INTO public.sales_orders (
      company_id,
      customer_id,
      customer_name,
      customer_email,
      customer_phone,
      shipping_address,
      order_date,
      status,
      total_amount,
      subtotal_amount,
      created_by
    ) VALUES (
      p_company_id,
      v_customer_orders.customer_id,
      v_customer_orders.customer_name,
      v_customer_orders.customer_email,
      v_customer_orders.customer_phone,
      v_customer_orders.customer_address,
      CURRENT_DATE,
      'confirmed',
      v_customer_orders.order_total,
      v_customer_orders.order_total,
      p_created_by
    ) RETURNING id INTO v_new_order_id;

    -- Create sales order items
    FOR i IN 1..array_length(v_customer_orders.product_ids, 1) LOOP
      INSERT INTO public.sales_order_items (
        sales_order_id,
        product_id,
        quantity,
        ordered_quantity,
        unit_price,
        total_price
      ) 
      SELECT 
        v_new_order_id,
        v_customer_orders.product_ids[i],
        v_customer_orders.quantities[i],
        v_customer_orders.quantities[i],
        v_customer_orders.unit_prices[i],
        v_customer_orders.quantities[i] * v_customer_orders.unit_prices[i];
    END LOOP;

    -- Update backorder items to fulfilled
    UPDATE public.backorder_items 
    SET status = 'fulfilled', updated_at = now()
    WHERE id = ANY(v_customer_orders.backorder_item_ids);

    v_processed_count := v_processed_count + array_length(v_customer_orders.backorder_item_ids, 1);
    v_total_value := v_total_value + v_customer_orders.order_total;
  END LOOP;

  v_result := json_build_object(
    'success', true,
    'processed_count', v_processed_count,
    'total_value', v_total_value,
    'orders_created', (SELECT COUNT(*) FROM unnest(p_backorder_ids))
  );

  RETURN v_result;
END;
$$;


--
-- Name: process_bom_production(uuid, integer, uuid, uuid, uuid, uuid); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.process_bom_production(p_bom_id uuid, p_quantity integer, p_company_id uuid, p_warehouse_id uuid, p_bin_id uuid DEFAULT NULL::uuid, p_created_by uuid DEFAULT NULL::uuid) RETURNS json
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_hdr RECORD;
  v_cmp RECORD;
  v_fg_qty INTEGER;
  v_material_cost_total NUMERIC := 0;
  v_labor_cost_total NUMERIC := 0;
  v_overhead_cost_total NUMERIC := 0;
  v_total_cost NUMERIC := 0;
  v_run_id UUID;
  v_component_qty INTEGER;
BEGIN
  IF p_quantity IS NULL OR p_quantity <= 0 THEN
    RAISE EXCEPTION 'Production quantity must be > 0';
  END IF;

  SELECT * INTO v_hdr
  FROM public.bom_headers
  WHERE id = p_bom_id AND company_id = p_company_id AND is_active = TRUE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'BOM not found or inactive';
  END IF;

  -- Compute totals
  v_fg_qty := COALESCE(v_hdr.yield_quantity, 1) * p_quantity;
  v_labor_cost_total := COALESCE(v_hdr.labor_cost_per_unit,0) * v_fg_qty;
  v_overhead_cost_total := COALESCE(v_hdr.overhead_cost_per_unit,0) * v_fg_qty;

  -- Consume components (production_consumption)
  FOR v_cmp IN
    SELECT bc.*, p.cost_price
    FROM public.bom_components bc
    JOIN public.products p ON p.id = bc.component_product_id
    WHERE bc.bom_id = p_bom_id
  LOOP
    -- Calculate component quantity as INTEGER
    v_component_qty := CEIL(v_cmp.quantity_per_unit * p_quantity)::INTEGER;
    
    PERFORM public.record_inventory_transaction(
      p_company_id,
      'production_consumption'::transaction_type,
      p_bom_id,
      v_hdr.bom_name,
      v_cmp.component_product_id,
      p_warehouse_id,
      p_bin_id,
      -v_component_qty,  -- negative integer for consumption
      v_cmp.unit_cost,
      'BOM Consumption - ' || v_hdr.bom_name,
      p_created_by
    );

    -- Update product stock for components
    UPDATE public.products
    SET stock_quantity = stock_quantity - v_component_qty,
        updated_at = now()
    WHERE id = v_cmp.component_product_id;

    v_material_cost_total := v_material_cost_total + (COALESCE(v_cmp.unit_cost,0) * v_component_qty);
  END LOOP;

  -- Receive finished goods (production_receipt)
  PERFORM public.record_inventory_transaction(
    p_company_id,
    'production_receipt'::transaction_type,
    p_bom_id,
    v_hdr.bom_name,
    v_hdr.finished_product_id,
    p_warehouse_id,
    p_bin_id,
    v_fg_qty,  -- positive integer for receipt
    COALESCE(v_hdr.total_cost_per_unit,0),
    'BOM Receipt - ' || v_hdr.bom_name,
    p_created_by
  );

  UPDATE public.products
  SET stock_quantity = stock_quantity + v_fg_qty,
      updated_at = now()
  WHERE id = v_hdr.finished_product_id;

  v_total_cost := v_material_cost_total + v_labor_cost_total + v_overhead_cost_total;

  INSERT INTO public.production_runs (
    company_id, bom_id, finished_product_id,
    warehouse_id, bin_id,
    quantity_produced, material_cost_total, labor_cost_total, overhead_cost_total, total_cost,
    created_by
  ) VALUES (
    p_company_id, p_bom_id, v_hdr.finished_product_id,
    p_warehouse_id, p_bin_id,
    v_fg_qty, v_material_cost_total, v_labor_cost_total, v_overhead_cost_total, v_total_cost,
    COALESCE(p_created_by, auth.uid())
  ) RETURNING id INTO v_run_id;

  RETURN json_build_object(
    'success', true,
    'production_run_id', v_run_id,
    'finished_goods_qty', v_fg_qty,
    'material_cost_total', v_material_cost_total,
    'labor_cost_total', v_labor_cost_total,
    'overhead_cost_total', v_overhead_cost_total,
    'total_cost', v_total_cost
  );
END;
$$;


--
-- Name: process_credit_note_inventory(uuid); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.process_credit_note_inventory(p_credit_note_id uuid) RETURNS json
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  credit_note_record RECORD;
  item_record RECORD;
  v_items_processed INTEGER := 0;
  v_transactions_created INTEGER := 0;
  error_msg TEXT;
  result JSON;
BEGIN
  -- Get credit note details
  SELECT * INTO credit_note_record FROM public.credit_notes WHERE id = p_credit_note_id;
  IF NOT FOUND THEN
    RETURN json_build_object(
      'success', false,
      'error', 'Credit note not found',
      'credit_note_id', p_credit_note_id
    );
  END IF;

  -- Only process confirmed credit notes
  IF credit_note_record.status != 'Confirmed' THEN
    RETURN json_build_object(
      'success', false,
      'error', 'Credit note is not confirmed',
      'status', credit_note_record.status
    );
  END IF;

  BEGIN
    -- Process each credit note item with return quantity > 0
    FOR item_record IN 
      SELECT * FROM public.credit_note_items 
      WHERE credit_note_id = p_credit_note_id AND return_qty > 0
    LOOP
      v_items_processed := v_items_processed + 1;
      
      -- Check if inventory transaction already exists to avoid duplicates
      IF NOT EXISTS (
        SELECT 1 FROM public.inventory_transactions 
        WHERE reference_id = p_credit_note_id 
        AND product_id = item_record.product_id
        AND transaction_type = 'sales_return'
      ) THEN
        -- Record inventory transaction for credit note return
        PERFORM public.record_inventory_transaction(
          credit_note_record.company_id,
          'sales_return'::transaction_type,
          p_credit_note_id,
          credit_note_record.cn_number,
          item_record.product_id,
          item_record.warehouse_id,
          item_record.bin_id,
          item_record.return_qty, -- Positive quantity for returns
          item_record.unit_price,
          'Credit Note Return - ' || item_record.product_name || ' (' || item_record.return_qty || ' units)',
          credit_note_record.created_by
        );
        
        v_transactions_created := v_transactions_created + 1;
      END IF;
    END LOOP;

    -- Update product stock quantities based on inventory transactions
    FOR item_record IN 
      SELECT DISTINCT product_id, warehouse_id, bin_id 
      FROM public.credit_note_items 
      WHERE credit_note_id = p_credit_note_id AND return_qty > 0
    LOOP
      -- Calculate actual stock from inventory transactions
      UPDATE public.products 
      SET stock_quantity = (
        SELECT COALESCE(SUM(quantity_change), 0) 
        FROM public.inventory_transactions 
        WHERE company_id = credit_note_record.company_id 
        AND product_id = item_record.product_id
      ),
      updated_at = now()
      WHERE id = item_record.product_id;
    END LOOP;

    result := json_build_object(
      'success', true,
      'credit_note_number', credit_note_record.cn_number,
      'items_processed', v_items_processed,
      'transactions_created', v_transactions_created
    );

  EXCEPTION WHEN OTHERS THEN
    error_msg := SQLERRM;
    result := json_build_object(
      'success', false,
      'error', error_msg,
      'credit_note_number', credit_note_record.cn_number,
      'items_processed', v_items_processed,
      'transactions_created', v_transactions_created
    );
  END;

  RETURN result;
END;
$$;


--
-- Name: process_grn_inventory(uuid); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.process_grn_inventory(p_grn_id uuid) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  hdr RECORD;
  li RECORD;
  already_processed_qty INTEGER;
  delta_qty INTEGER;
  total_pending INTEGER;
  new_status TEXT;
BEGIN
  -- Load header; exit if not found
  SELECT * INTO hdr FROM public.grn_header WHERE id = p_grn_id;
  IF NOT FOUND THEN
    RETURN;
  END IF;

  -- Only process when GRN is in a received/accepted state
  IF hdr.status NOT IN ('accepted','received','partially_received') THEN
    RETURN;
  END IF;

  -- For each line item, compute delta between accepted and already processed inventory qty
  FOR li IN 
    SELECT * FROM public.grn_line_items WHERE grn_header_id = p_grn_id
  LOOP
    SELECT COALESCE(SUM(it.quantity_change), 0)
      INTO already_processed_qty
    FROM public.inventory_transactions it
    WHERE it.transaction_type = 'purchase_receipt'
      AND it.reference_id = p_grn_id
      AND it.product_id = li.product_id;

    delta_qty := COALESCE(li.accepted_quantity, 0) - COALESCE(already_processed_qty, 0);

    -- If there is any delta (positive or negative), reconcile inventory and PO item quantities
    IF delta_qty <> 0 THEN
      -- Update product stock
      UPDATE public.products 
      SET stock_quantity = stock_quantity + delta_qty,
          updated_at = now()
      WHERE id = li.product_id;

      -- Update related PO item received/pending using the delta
      UPDATE public.purchase_order_items poi
      SET received_quantity = GREATEST(0, received_quantity + delta_qty),
          pending_quantity = GREATEST(0, quantity - (received_quantity + delta_qty))
      WHERE poi.purchase_order_id = hdr.purchase_order_id
        AND poi.product_id = li.product_id;

      -- Record the inventory transaction for the delta
      PERFORM public.record_inventory_transaction(
        hdr.company_id,
        'purchase_receipt'::transaction_type,
        hdr.id,
        hdr.grn_number,
        li.product_id,
        li.warehouse_id,
        li.bin_id,
        delta_qty,
        li.unit_price,
        'GRN Receipt - ' || hdr.grn_number,
        NULL -- created_by (use auth.uid())
      );
    END IF;
  END LOOP;

  -- Recompute PO status after adjustments
  SELECT COALESCE(SUM(pending_quantity), 0)
    INTO total_pending
  FROM public.purchase_order_items 
  WHERE purchase_order_id = hdr.purchase_order_id;

  IF total_pending = 0 THEN
    new_status := 'closed';
  ELSIF EXISTS (
    SELECT 1 FROM public.purchase_order_items 
    WHERE purchase_order_id = hdr.purchase_order_id AND received_quantity > 0
  ) THEN
    new_status := 'partially_received';
  ELSE
    new_status := 'open';
  END IF;

  UPDATE public.purchase_orders 
  SET status = new_status,
      updated_at = now()
  WHERE id = hdr.purchase_order_id;

END;
$$;


--
-- Name: process_grn_inventory_enhanced(uuid); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.process_grn_inventory_enhanced(p_grn_id uuid) RETURNS json
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  hdr RECORD;
  li RECORD;
  already_processed_qty INTEGER;
  delta_qty INTEGER;
  total_pending INTEGER;
  new_status TEXT;
  v_items_processed INTEGER := 0;
  v_transactions_created INTEGER := 0;
  error_msg TEXT;
  result JSON;
BEGIN
  -- Load header; exit if not found
  SELECT * INTO hdr FROM public.grn_header WHERE id = p_grn_id;
  IF NOT FOUND THEN
    RETURN json_build_object(
      'success', false,
      'error', 'GRN not found',
      'grn_id', p_grn_id
    );
  END IF;

  BEGIN
    -- Only process when GRN is in a received/accepted state
    IF hdr.status NOT IN ('accepted','received','partially_received') THEN
      RETURN json_build_object(
        'success', false,
        'error', 'GRN status not eligible for processing',
        'status', hdr.status,
        'grn_number', hdr.grn_number
      );
    END IF;

    -- For each line item, compute delta between accepted and already processed inventory qty
    FOR li IN 
      SELECT * FROM public.grn_line_items WHERE grn_header_id = p_grn_id
    LOOP
      v_items_processed := v_items_processed + 1;
      
      -- Validate warehouse exists
      IF li.warehouse_id IS NULL THEN
        RAISE EXCEPTION 'Missing warehouse_id for item: %', li.product_name;
      END IF;
      
      SELECT COALESCE(SUM(it.quantity_change), 0)
        INTO already_processed_qty
      FROM public.inventory_transactions it
      WHERE it.transaction_type = 'purchase_receipt'
        AND it.reference_id = p_grn_id
        AND it.product_id = li.product_id;

      delta_qty := COALESCE(li.accepted_quantity, 0) - COALESCE(already_processed_qty, 0);

      -- If there is any delta (positive or negative), reconcile inventory and PO item quantities
      IF delta_qty <> 0 THEN
        -- Update product stock
        UPDATE public.products 
        SET stock_quantity = stock_quantity + delta_qty,
            updated_at = now()
        WHERE id = li.product_id;

        -- Update related PO item received/pending using the delta
        UPDATE public.purchase_order_items poi
        SET received_quantity = GREATEST(0, received_quantity + delta_qty),
            pending_quantity = GREATEST(0, quantity - (received_quantity + delta_qty))
        WHERE poi.purchase_order_id = hdr.purchase_order_id
          AND poi.product_id = li.product_id;

        -- Record the inventory transaction for the delta
        PERFORM public.record_inventory_transaction(
          hdr.company_id,
          'purchase_receipt'::transaction_type,
          hdr.id,
          hdr.grn_number,
          li.product_id,
          li.warehouse_id,
          li.bin_id,
          delta_qty,
          li.unit_price,
          'GRN Receipt - ' || hdr.grn_number,
          NULL -- created_by (use auth.uid())
        );
        
        v_transactions_created := v_transactions_created + 1;
      END IF;
    END LOOP;

    -- Recompute PO status after adjustments
    SELECT COALESCE(SUM(pending_quantity), 0)
      INTO total_pending
    FROM public.purchase_order_items 
    WHERE purchase_order_id = hdr.purchase_order_id;

    IF total_pending = 0 THEN
      new_status := 'closed';
    ELSIF EXISTS (
      SELECT 1 FROM public.purchase_order_items 
      WHERE purchase_order_id = hdr.purchase_order_id AND received_quantity > 0
    ) THEN
      new_status := 'partially_received';
    ELSE
      new_status := 'open';
    END IF;

    UPDATE public.purchase_orders 
    SET status = new_status,
        updated_at = now()
    WHERE id = hdr.purchase_order_id;

    result := json_build_object(
      'success', true,
      'grn_number', hdr.grn_number,
      'items_processed', v_items_processed,
      'transactions_created', v_transactions_created,
      'po_status', new_status
    );

  EXCEPTION WHEN OTHERS THEN
    error_msg := SQLERRM;
    result := json_build_object(
      'success', false,
      'error', error_msg,
      'grn_number', hdr.grn_number,
      'items_processed', v_items_processed,
      'transactions_created', v_transactions_created
    );
  END;

  RETURN result;
END;
$$;


--
-- Name: process_sales_invoice(uuid); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.process_sales_invoice(p_invoice_id uuid) RETURNS json
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
    invoice_record RECORD;
    item_record RECORD;
    v_items_processed INTEGER := 0;
    v_transactions_created INTEGER := 0;
    error_msg TEXT;
    result JSON;
    missing_warehouse_items TEXT := '';
BEGIN
    -- Load invoice record
    SELECT * INTO invoice_record FROM public.sales_invoices WHERE id = p_invoice_id;
    IF NOT FOUND THEN
        RETURN json_build_object(
            'success', false,
            'error', 'Sales invoice not found',
            'invoice_id', p_invoice_id
        );
    END IF;

    BEGIN
        -- Only process when invoice is finalized
        IF invoice_record.status NOT IN ('finalized') THEN
            RETURN json_build_object(
                'success', false,
                'error', 'Invoice status not eligible for processing',
                'status', invoice_record.status,
                'invoice_number', invoice_record.invoice_number
            );
        END IF;

        -- Check for missing warehouse_id in finalized invoices
        SELECT string_agg(sii.item_description, ', ')
        INTO missing_warehouse_items
        FROM public.sales_invoice_items sii
        WHERE sii.sales_invoice_id = p_invoice_id 
        AND sii.warehouse_id IS NULL;

        IF missing_warehouse_items IS NOT NULL AND missing_warehouse_items != '' THEN
            RETURN json_build_object(
                'success', false,
                'error', 'Missing warehouse information for items: ' || missing_warehouse_items,
                'invoice_number', invoice_record.invoice_number
            );
        END IF;

        -- Process each invoice item
        FOR item_record IN 
            SELECT * FROM public.sales_invoice_items WHERE sales_invoice_id = p_invoice_id
        LOOP
            v_items_processed := v_items_processed + 1;
            
            -- Update product stock (reduce by invoiced quantity)
            UPDATE public.products 
            SET stock_quantity = stock_quantity - item_record.quantity_invoiced,
                updated_at = now()
            WHERE id = item_record.product_id;

            -- Record inventory transaction for sales invoice
            PERFORM public.record_inventory_transaction(
                invoice_record.company_id,
                'sales_invoice'::transaction_type,
                invoice_record.id,
                invoice_record.invoice_number,
                item_record.product_id,
                item_record.warehouse_id,
                item_record.bin_id,
                -item_record.quantity_invoiced, -- negative for sales
                item_record.unit_price,
                'Sales Invoice - ' || invoice_record.invoice_number,
                NULL -- created_by: use session user (auth.uid())
            );
            
            v_transactions_created := v_transactions_created + 1;
        END LOOP;

        -- NOTE: We no longer update sales order status here
        -- Sales order status must be managed independently

        result := json_build_object(
            'success', true,
            'invoice_number', invoice_record.invoice_number,
            'items_processed', v_items_processed,
            'transactions_created', v_transactions_created
        );

    EXCEPTION WHEN OTHERS THEN
        error_msg := SQLERRM;
        result := json_build_object(
            'success', false,
            'error', error_msg,
            'invoice_number', invoice_record.invoice_number,
            'items_processed', v_items_processed,
            'transactions_created', v_transactions_created
        );
    END;

    RETURN result;
END;
$$;


--
-- Name: record_inventory_transaction(uuid, public.transaction_type, uuid, text, uuid, uuid, uuid, integer, numeric, text, uuid); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.record_inventory_transaction(p_company_id uuid, p_transaction_type public.transaction_type, p_reference_id uuid, p_reference_number text, p_product_id uuid, p_warehouse_id uuid, p_bin_id uuid, p_quantity_change integer, p_unit_cost numeric DEFAULT 0, p_notes text DEFAULT NULL::text, p_created_by uuid DEFAULT NULL::uuid) RETURNS uuid
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  transaction_id UUID;
  calculated_total_value NUMERIC;
  effective_created_by UUID;
BEGIN
  -- Total value for this delta
  calculated_total_value := COALESCE(p_quantity_change, 0) * COALESCE(p_unit_cost, 0);

  -- Created by: provided -> auth.uid() -> fallback to first profile in company
  effective_created_by := COALESCE(p_created_by, auth.uid());
  IF effective_created_by IS NULL THEN
    SELECT user_id INTO effective_created_by
    FROM public.profiles
    WHERE company_id = p_company_id
    LIMIT 1;
  END IF;

  -- Insert or update existing transaction for the same (company, reference, product, type)
  INSERT INTO public.inventory_transactions (
    company_id,
    transaction_type,
    reference_id,
    reference_number,
    product_id,
    warehouse_id,
    bin_id,
    quantity_change,
    unit_cost,
    total_value,
    notes,
    created_by
  ) VALUES (
    p_company_id,
    p_transaction_type,
    p_reference_id,
    p_reference_number,
    p_product_id,
    p_warehouse_id,
    p_bin_id,
    COALESCE(p_quantity_change, 0),
    COALESCE(p_unit_cost, 0),
    COALESCE(calculated_total_value, 0),
    p_notes,
    effective_created_by
  )
  ON CONFLICT ON CONSTRAINT uq_inventory_tx_unique_ref
  DO UPDATE
    SET
      quantity_change = public.inventory_transactions.quantity_change + EXCLUDED.quantity_change,
      total_value     = public.inventory_transactions.total_value + EXCLUDED.total_value,
      -- keep a reasonable unit_cost (weighted average when possible)
      unit_cost       = CASE
                          WHEN NULLIF(public.inventory_transactions.quantity_change + EXCLUDED.quantity_change, 0) IS NULL
                            THEN EXCLUDED.unit_cost
                          ELSE
                            (public.inventory_transactions.total_value + EXCLUDED.total_value)
                            / NULLIF(public.inventory_transactions.quantity_change + EXCLUDED.quantity_change, 0)
                        END,
      notes           = COALESCE(EXCLUDED.notes, public.inventory_transactions.notes),
      updated_at      = now()
  RETURNING id INTO transaction_id;

  RETURN transaction_id;
END;
$$;


